/** where a run was measured - hosted runners don't all have the same CPU */
function machineOf(entry: HistoryEntry) {
  return entry.runner ? `${entry.runner} · ${entry.machine}` : entry.machine;
}

function installedVersion(name: string) {
  try {
    const pkg = JSON.parse(
      fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'),
    );
    return (pkg.dependencies?.[name] as string) ?? null;
  } catch {
    return null;
  }
}

/** e.g. "**Infinite Table 10.1.5** vs **AG Grid React 36.3.0**, ... and ..." */
function describeVersions(entry: HistoryEntry) {
  const describe: Record<GridName, (version: string) => string> = {
    infinite: (v) => `**Infinite Table ${v}**`,
    'ag-grid': (v) => `**AG Grid React ${v}** (Community)`,
    mui: (v) => `**MUI X Data Grid ${v}** (the free \`DataGrid\`)`,
    tanstack: (v) => {
      const virtual = installedVersion('@tanstack/react-virtual');
      return `**TanStack Table ${v}** (with TanStack Virtual${
        virtual ? ` ${virtual}` : ''
      })`;
    },
  };
  const others = GRID_NAMES.filter(
    (grid) => grid !== 'infinite' && entry.versions[grid],
  ).map((grid) => describe[grid](entry.versions[grid]!));
  const list =
    others.length > 1
      ? `${others.slice(0, -1).join(', ')} and ${others[others.length - 1]}`
      : others[0];
  return `${describe.infinite(entry.versions.infinite ?? '')} vs ${list}`;
}

function buildReadmeSection(latest: HistoryEntry, history: HistoryEntry[]) {
  const out: string[] = [];
  const date = latest.date.slice(0, 10);
  const where = latest.runner
    ? `${latest.runner} (${latest.machine})`
    : `${latest.machine}, ${latest.os}`;

  out.push(`## Results`);
  out.push('');
  out.push(
    `${describeVersions(latest)} - ` +
      `measured on ${date}, on ${where}, in Chrome ${latest.chrome}${
        latest.headless ? ' (headless)' : ''
      }. Every value is the median of ${latest.runs} runs.`,
  );
  out.push('');
  out.push(
    `The absolute numbers depend on the machine - compare the grids, not the milliseconds. ` +
      `In the table under the charts, a difference is only called when the 95% confidence interval excludes "no difference".`,
  );

  const summaryRows: string[] = [];
  const measured = GRID_NAMES.filter((grid) => latest.versions[grid]);

  for (const spec of CHARTS) {
    const rows: ChartRow[] = spec.rows
      .filter((row) => latest.metrics[row.id])
      .map((row) => ({ ...row, summary: latest.metrics[row.id] }));
    if (!rows.length) {
      continue;
    }
    const { unit, better } = rows[0].summary;
    const caption = `${spec.subtitle} · ${
      unit === '%' ? 'percent' : unit
    } · ${better} is better`;

    fs.mkdirSync(CHARTS_DIR, { recursive: true });
    for (const themeName of ['light', 'dark'] as const) {
      fs.writeFileSync(
        path.join(CHARTS_DIR, `${spec.file}-${themeName}.svg`),
        renderChart(spec, rows, caption, themeName),
      );
    }

    const grids = gridsOfChart(rows);
    const alt = `${spec.title} (${better} is better). ${rows
      .map(
        (row) =>
          `${row.label}: ${grids
            .filter((grid) => row.summary.values[grid] != null)
            .map(
              (grid) =>
                `${GRID_FULL_NAMES[grid]} ${formatValue(
                  row.summary.values[grid]!,
                  unit,
                )}`,
            )
            .join(', ')}`,
      )
      .join('; ')}.`;
    const src = (themeName: string) =>
      `results/latest/charts/${spec.file}-${themeName}.svg`;
    out.push('');
    out.push(
      `<picture>\n` +
        `  <source media="(prefers-color-scheme: dark)" srcset="${src(
          'dark',
        )}">\n` +
        `  <img src="${src('light')}" width="${CHART.width}" alt="${alt.replace(
          /"/g,
          '&quot;',
        )}">\n` +
        `</picture>`,
    );
    if (spec.note) {
      out.push('');
      out.push(spec.note);
    }

    // the "at a glance" rows come back in the charts that follow
    if (spec.file !== 'at-a-glance') {
      for (const row of rows) {
        summaryRows.push(
          `| ${spec.context} - ${row.label} | ${measured
            .map((grid) => {
              const value = row.summary.values[grid];
              return value == null ? '–' : formatValue(value, unit);
            })
            .join(' | ')} | ${describeDifferences(row.summary)} |`,
        );
      }
    }
  }

  out.push('');
  out.push(`<details>`);
  out.push(
    `<summary>The same numbers, as a table - and how Infinite Table compares with each grid</summary>`,
  );
  out.push('');
  out.push(
    `| | ${measured
      .map((grid) => GRID_FULL_NAMES[grid])
      .join(' | ')} | Infinite Table vs each grid |`,
  );
  out.push(`|---|${measured.map(() => '---:').join('|')}|---|`);
  out.push(...summaryRows);
  out.push('');
  out.push(`</details>`);
  out.push('');
  out.push(
    `Every metric of every scenario, with standard deviations and confidence intervals: ` +
      `[full report](./results/latest/report.md) · [raw samples](./results/latest/results.json).`,
  );

  out.push('');
  out.push(`## History`);
  out.push('');
  out.push(
    `Every set of versions measured so far, newest first, with a row for each grid. ` +
      `All the values are times in ms, except memory, in MB - lower is better. ` +
      `Runs measured on different machines can't be compared in absolute terms (hosted runners don't all have the same CPU) - compare how the grids relate within a run. ` +
      `The branch of a run has the code, the lockfile and the full results of that run.`,
  );
  out.push('');
  out.push(
    `| Run | Grid | ${HISTORY_COLUMNS.map((c) => c.label).join(' | ')} |`,
  );
  out.push(`|---|---|${HISTORY_COLUMNS.map(() => '---:').join('|')}|`);
  for (const entry of history) {
    const branch = versionBranch(entry);
    const run =
      `${entry.date.slice(0, 10)}<br>${machineOf(entry)}<br>` +
      `[branch](${REPO_URL}/tree/${branch})`;
    // Infinite Table first, then the others
    const grids = VERSION_ORDER.filter((grid) => entry.versions[grid]);
    grids.forEach((grid, index) => {
      const cells = HISTORY_COLUMNS.map((column) => {
        const value = entry.metrics[column.id]?.values[grid];
        return value == null ? '–' : formatNumber(value);
      });
      out.push(
        `| ${index === 0 ? run : ''} | ${GRID_FULL_NAMES[grid]} ${
          entry.versions[grid]
        } | ${cells.join(' | ')} |`,
      );
    });
  }

  return out.join('\n');
}

function updateReadme(section: string) {
  const readme = fs.readFileSync(README_FILE, 'utf8');
  const start = readme.indexOf(MARKER_START);
  const end = readme.indexOf(MARKER_END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(
      `README.md needs the "${MARKER_START}" and "${MARKER_END}" markers`,
    );
  }
  fs.writeFileSync(
    README_FILE,
    readme.slice(0, start) +
      MARKER_START +
      '\n\n' +
      section +
      '\n\n' +
      readme.slice(end),
  );
}

