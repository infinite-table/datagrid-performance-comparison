function findRun(runId: string | undefined) {
  if (runId) {
    return path.join(RUNS_DIR, runId);
  }
  const runs = fs
    .readdirSync(RUNS_DIR, { withFileTypes: true })
    .filter(
      (d) =>
        d.isDirectory() &&
        fs.existsSync(path.join(RUNS_DIR, d.name, 'results.json')),
    )
    .map((d) => ({
      dir: path.join(RUNS_DIR, d.name),
      time: fs.statSync(path.join(RUNS_DIR, d.name, 'results.json')).mtimeMs,
    }))
    .sort((a, b) => b.time - a.time);
  if (!runs.length) {
    throw new Error(`No run with a results.json in ${RUNS_DIR}`);
  }
  return runs[0].dir;
}

function readResults(dir: string): StoredResults {
  return JSON.parse(fs.readFileSync(path.join(dir, 'results.json'), 'utf8'));
}

const sameVersions = (a: HistoryEntry, b: HistoryEntry) =>
  GRID_NAMES.every((grid) => a.versions[grid] === b.versions[grid]);

function main() {
  const args = process.argv.slice(2);
  const readmeOnly = args.includes('--readme-only');
  const historyOnly = args.includes('--history-only');
  const runId = args.find((arg) => !arg.startsWith('--'));

  let history: HistoryEntry[] = fs.existsSync(HISTORY_FILE)
    ? JSON.parse(fs.readFileSync(HISTORY_FILE, 'utf8')).map(normalizeEntry)
    : [];
  // a set of versions that is measured again replaces its earlier run
  const record = (entry: HistoryEntry) => {
    history = [entry, ...history.filter((e) => !sameVersions(e, entry))];
    return entry;
  };

  if (!readmeOnly) {
    const runDir = findRun(runId);
    record(toHistoryEntry(readResults(runDir)));
    if (!historyOnly) {
      fs.rmSync(LATEST_DIR, { recursive: true, force: true });
      fs.mkdirSync(LATEST_DIR, { recursive: true });
      for (const file of ['report.md', 'results.json']) {
        fs.copyFileSync(path.join(runDir, file), path.join(LATEST_DIR, file));
      }
    }
    console.log(
      `${historyOnly ? 'history' : 'results/latest'} <- ${path.relative(
        ROOT,
        runDir,
      )}`,
    );
  }

  // what the README shows is always the run in results/latest
  const latestRun = toHistoryEntry(readResults(LATEST_DIR));
  const latest =
    history.find((entry) => sameVersions(entry, latestRun)) ??
    record(latestRun);

  history.sort((a, b) => {
    for (const grid of VERSION_ORDER) {
      const order = compareVersions(b.versions[grid], a.versions[grid]);
      if (order) {
        return order;
      }
    }
    return 0;
  });
  fs.writeFileSync(HISTORY_FILE, JSON.stringify(history, null, 2) + '\n');

  fs.rmSync(CHARTS_DIR, { recursive: true, force: true });
  updateReadme(buildReadmeSection(latest, history));
  console.log(
    `README.md, results/history.json and results/latest/charts updated - ` +
      VERSION_ORDER.filter((grid) => latest.versions[grid])
        .map((grid) => `${GRID_FULL_NAMES[grid]} ${latest.versions[grid]}`)
        .join(', '),
  );
}

main();
