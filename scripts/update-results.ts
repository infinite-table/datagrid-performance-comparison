function toHistoryEntry(stored: StoredResults): HistoryEntry {
  const env = stored.environment;
  const metrics: Record<string, Summary> = {};
  for (const [size, sizeResults] of Object.entries(stored.sizes)) {
    for (const result of Object.values(sizeResults.results)) {
      for (const s of summarize(result)) {
        const values: Summary['values'] = {};
        for (const grid of GRID_NAMES) {
          if (s.grids[grid]) {
            values[grid] = s.grids[grid].median;
          }
        }
        const winners: Summary['winners'] = {};
        for (const other of OTHER_GRID_NAMES) {
          if (s.vs[other]) {
            winners[other] = s.vs[other].winner ?? '≈';
          }
        }
        metrics[`${size}/${result.scenario}/${s.metric.key}`] = {
          values,
          winners,
          unit: s.metric.unit,
          better: s.metric.better,
        };
      }
    }
  }
  return {
    versions: env.versions,
    date: env.date,
    chrome: env.chrome,
    headless: env.headless,
    runs: env.runs,
    machine: env.cpu,
    os: env.os,
    runner: process.env.BENCH_RUNNER || null,
    metrics,
  };
}

/** numeric, so 10.10.0 is newer than 10.9.0 */
function compareVersions(a: string | undefined, b: string | undefined) {
  return (a ?? '').localeCompare(b ?? '', 'en', { numeric: true });
}

// Infinite Table first: the history is sorted by its version, and the
// branches are named after it - keep in sync with scripts/check-versions.mjs
const VERSION_ORDER: GridName[] = ['infinite', 'ag-grid', 'mui', 'tanstack'];

function versionBranch(entry: HistoryEntry) {
  return `versions/${VERSION_ORDER.filter((grid) => entry.versions[grid])
    .map((grid) => `${grid}-${entry.versions[grid]}`)
    .join('_')}`;
}

