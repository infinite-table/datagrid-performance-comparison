function formatNumber(value: number) {
  if (!Number.isFinite(value)) {
    return '–';
  }
  const abs = Math.abs(value);
  return value.toLocaleString('en-US', {
    maximumFractionDigits: abs >= 100 ? 0 : abs >= 10 ? 1 : 2,
  });
}

function formatValue(value: number, unit: string) {
  const text = formatNumber(value);
  if (!unit || text === '–') {
    return text;
  }
  return unit === '%' ? `${text}%` : `${text} ${unit}`;
}

/** e.g. "Infinite Table: 31% lower", or "no significant difference" */
function describeDifference(s: Summary) {
  if (s.winner === '≈') {
    return 'no significant difference';
  }
  const infiniteWins = s.winner === 'Infinite';
  const name = infiniteWins ? '**Infinite Table**' : '**AG Grid**';
  const winner = infiniteWins ? s.infinite : s.ag;
  const other = infiniteWins ? s.ag : s.infinite;
  if (s.unit === '%') {
    // already a percentage - give the difference in points
    const points = formatNumber(Math.abs(winner - other));
    return `${name}: ${points} points ${s.better}`;
  }
  const base = s.better === 'lower' ? other : winner;
  if (!base) {
    return `${name}: ${s.better}`;
  }
  const ratio = s.better === 'lower' ? other / winner : winner / other;
  if (Number.isFinite(ratio) && ratio >= 2) {
    return `${name}: ${formatNumber(ratio)}× ${s.better}`;
  }
  const pct = Math.round((Math.abs(winner - other) / other) * 100);
  return `${name}: ${pct}% ${s.better}`;
}

const escapeXml = (text: string) =>
  text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

