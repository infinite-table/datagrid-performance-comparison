/**
 * Turns the results of a benchmark run into what the repository shows:
 *
 *  - results/latest/           report.md + results.json of the run
 *  - results/latest/charts/    one SVG per chart, for GitHub's light and dark themes
 *  - results/history.json      the medians of every set of versions measured so far
 *  - README.md                 the part between the `results:start` / `results:end` markers
 *
 * Usage (Node.js 22.18+, which runs TypeScript files as they are):
 *
 *   node scripts/update-results.ts                 # the most recent run in benchmark-results/
 *   node scripts/update-results.ts <run id>        # benchmark-results/<run id>
 *   node scripts/update-results.ts <run id> --history-only
 *                                                  # older versions: only their rows in the
 *                                                  # history - results/latest stays as it is
 *   node scripts/update-results.ts --readme-only   # rebuild charts + README from results/
 *
 * Env: BENCH_RUNNER - where it ran, e.g. "GitHub Actions, ubuntu-24.04"
 */
