type ChartRow = Row & { summary: Summary };

const CHART = {
  width: 760,
  padding: 20,
  /** the names of the grids, at the left of the bars */
  nameWidth: 118,
  /** room kept at the right of the longest bar, for its value */
  valueSpace: 110,
  barHeight: 14,
  barGap: 4,
  rowGap: 30,
  labelHeight: 20,
  radius: 4,
};

/** a bar anchored at the baseline: square at the left, rounded at the data end */
function barPath(x: number, y: number, width: number, height: number) {
  const r = Math.min(CHART.radius, width);
  const right = x + width;
  return (
    `M${x},${y}H${right - r}` +
    `a${r},${r} 0 0 1 ${r},${r}V${y + height - r}` +
    `a${r},${r} 0 0 1 ${-r},${r}H${x}Z`
  );
}

/** the grids that have a value in at least one of the rows */
function gridsOfChart(rows: ChartRow[]) {
  return GRID_NAMES.filter((grid) =>
    rows.some((row) => row.summary.values[grid] != null),
  );
}

function renderChart(
  spec: ChartSpec,
  rows: ChartRow[],
  caption: string,
  themeName: keyof typeof THEMES,
) {
  const theme = THEMES[themeName];
  const { width, padding, barHeight, barGap } = CHART;
  const font = `font-family="system-ui, -apple-system, 'Segoe UI', Helvetica, Arial, sans-serif"`;
  const grids = gridsOfChart(rows);
  const max = Math.max(
    ...rows.flatMap((row) =>
      grids.map((grid) => row.summary.values[grid] ?? 0),
    ),
    0,
  );
  const barLeft = padding + CHART.nameWidth;
  const barMax = width - padding - barLeft - CHART.valueSpace;
  const out: string[] = [];

  let y = padding + 16;
  out.push(
    `<text x="${padding}" y="${y}" ${font} font-size="16" font-weight="600" fill="${
      theme.text
    }">${escapeXml(spec.title)}</text>`,
  );
  y += 20;
  out.push(
    `<text x="${padding}" y="${y}" ${font} font-size="13" fill="${
      theme.textMuted
    }">${escapeXml(caption)}</text>`,
  );
  y += 4;

  for (const row of rows) {
    y += CHART.rowGap;
    out.push(
      `<text x="${padding}" y="${y}" ${font} font-size="13" font-weight="600" fill="${
        theme.textSecondary
      }">${escapeXml(row.label)}</text>`,
    );
    y += CHART.labelHeight - 12;
    const top = y;
    for (const grid of grids) {
      const value = row.summary.values[grid];
      // the name of the grid: identity is never carried by color alone
      out.push(
        `<text x="${padding}" y="${y + barHeight - 2.5}" ${font} font-size="13" fill="${
          theme.textSecondary
        }">${escapeXml(GRID_FULL_NAMES[grid])}</text>`,
      );
      if (value == null) {
        out.push(
          `<text x="${barLeft + 8}" y="${
            y + barHeight - 2.5
          }" ${font} font-size="13" fill="${theme.textMuted}">not measured</text>`,
        );
      } else {
        const barWidth = max > 0 ? Math.max(1, (value / max) * barMax) : 1;
        out.push(
          `<path d="${barPath(
            barLeft,
            y,
            Math.round(barWidth * 10) / 10,
            barHeight,
          )}" fill="${theme[grid]}"/>`,
          `<text x="${Math.round(barLeft + barWidth + 8)}" y="${
            y + barHeight - 2.5
          }" ${font} font-size="13" fill="${theme.text}">${escapeXml(
            formatValue(value, row.summary.unit),
          )}</text>`,
        );
      }
      y += barHeight + barGap;
    }
    y -= barGap;
    // the baseline the bars grow from
    out.push(
      `<line x1="${barLeft - 0.5}" y1="${top - 2}" x2="${barLeft - 0.5}" y2="${
        y + 2
      }" stroke="${theme.baseline}" stroke-width="1"/>`,
    );
  }

  const height = y + padding;
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img">\n` +
    `<title>${escapeXml(spec.title)}</title>\n` +
    `<rect x="0.5" y="0.5" width="${width - 1}" height="${
      height - 1
    }" rx="10" fill="${theme.surface}" stroke="${theme.border}"/>\n` +
    out.join('\n') +
    `\n</svg>\n`
  );
}

