/** where a run was measured - hosted runners don't all have the same CPU */
function machineOf(entry: HistoryEntry) {
  return entry.runner ? `${entry.runner} · ${entry.machine}` : entry.machine;
}

function buildReadmeSection(latest: HistoryEntry, history: HistoryEntry[]) {
  const out: string[] = [];
  const date = latest.date.slice(0, 10);
  const where = latest.runner
    ? `${latest.runner} (${latest.machine})`
    : `${latest.machine}, ${latest.os}`;

  out.push(`## Results`);
  out.push('');
  out.push(
    `**Infinite Table ${latest.infinite}** vs **AG Grid React ${latest.agGrid}** - ` +
      `measured on ${date}, on ${where}, in Chrome ${latest.chrome}${
        latest.headless ? ' (headless)' : ''
      }. Every value is the median of ${latest.runs} runs.`,
  );
  out.push('');
  out.push(
    `The absolute numbers depend on the machine - compare the two grids, not the milliseconds. ` +
      `A difference is only called when the 95% confidence interval excludes "no difference".`,
  );

  const summaryRows: string[] = [];

  for (const spec of CHARTS) {
    const rows: ChartRow[] = spec.rows
      .filter((row) => latest.metrics[row.id])
      .map((row) => ({ ...row, summary: latest.metrics[row.id] }));
    if (!rows.length) {
      continue;
    }
    const { unit, better } = rows[0].summary;
    const caption = `${spec.subtitle} · ${
      unit === '%' ? 'percent' : unit
    } · ${better} is better`;

    fs.mkdirSync(CHARTS_DIR, { recursive: true });
    for (const themeName of ['light', 'dark'] as const) {
      fs.writeFileSync(
        path.join(CHARTS_DIR, `${spec.file}-${themeName}.svg`),
        renderChart(spec, rows, caption, themeName),
      );
    }

    const alt = `${spec.title} (${better} is better). ${rows
      .map(
        (row) =>
          `${row.label}: AG Grid ${formatValue(
            row.summary.ag,
            unit,
          )}, Infinite Table ${formatValue(row.summary.infinite, unit)}`,
      )
      .join('; ')}.`;
    const src = (themeName: string) =>
      `results/latest/charts/${spec.file}-${themeName}.svg`;
    out.push('');
    out.push(
      `<picture>\n` +
        `  <source media="(prefers-color-scheme: dark)" srcset="${src(
          'dark',
        )}">\n` +
        `  <img src="${src('light')}" width="${CHART.width}" alt="${alt.replace(
          /"/g,
          '&quot;',
        )}">\n` +
        `</picture>`,
    );

    // the "at a glance" rows come back in the charts that follow
    if (spec.file !== 'at-a-glance') {
      for (const row of rows) {
        summaryRows.push(
          `| ${spec.context} - ${row.label} | ${formatValue(
            row.summary.ag,
            unit,
          )} | ${formatValue(
            row.summary.infinite,
            unit,
          )} | ${describeDifference(row.summary)} |`,
        );
      }
    }
  }

  out.push('');
  out.push(`<details>`);
  out.push(`<summary>The same numbers, as a table</summary>`);
  out.push('');
  out.push(`| | AG Grid | Infinite Table | Difference |`);
  out.push(`|---|---:|---:|---|`);
  out.push(...summaryRows);
  out.push('');
  out.push(`</details>`);
  out.push('');
  out.push(
    `Every metric of every scenario, with standard deviations and confidence intervals: ` +
      `[full report](./results/latest/report.md) · [raw samples](./results/latest/results.json).`,
  );

  out.push('');
  out.push(`## History`);
  out.push('');
  out.push(
    `One row for every pair of versions measured so far, newest first. ` +
      `Each cell is **Infinite Table / AG Grid**; all are times in ms, except memory, in MB - lower is better. ` +
      `Rows measured on different machines can't be compared in absolute terms (hosted runners don't all have the same CPU) - compare how the two grids relate. ` +
      `The branch of a row has the code, the lockfile and the full results of that run.`,
  );
  out.push('');
  out.push(
    `| Infinite Table | AG Grid | Date | ${HISTORY_COLUMNS.map(
      (c) => c.label,
    ).join(' | ')} | Machine | Results |`,
  );
  out.push(
    `|---|---|---|${HISTORY_COLUMNS.map(() => '---:').join('|')}|---|---|`,
  );
  for (const entry of history) {
    const cells = HISTORY_COLUMNS.map((column) => {
      const m = entry.metrics[column.id];
      return m ? `${formatNumber(m.infinite)} / ${formatNumber(m.ag)}` : '–';
    });
    const branch = versionBranch(entry);
    out.push(
      `| ${entry.infinite} | ${entry.agGrid} | ${entry.date.slice(
        0,
        10,
      )} | ${cells.join(' | ')} | ${machineOf(
        entry,
      )} | [branch](${REPO_URL}/tree/${branch}) |`,
    );
  }

  return out.join('\n');
}

function updateReadme(section: string) {
  const readme = fs.readFileSync(README_FILE, 'utf8');
  const start = readme.indexOf(MARKER_START);
  const end = readme.indexOf(MARKER_END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(
      `README.md needs the "${MARKER_START}" and "${MARKER_END}" markers`,
    );
  }
  fs.writeFileSync(
    README_FILE,
    readme.slice(0, start) +
      MARKER_START +
      '\n\n' +
      section +
      '\n\n' +
      readme.slice(end),
  );
}

