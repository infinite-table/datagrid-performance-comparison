// the two series colors were checked for colorblind separation and contrast
// on each surface; text never takes a series color
const THEMES = {
  light: {
    surface: '#ffffff',
    border: '#d1d9e0',
    baseline: '#c3c2b7',
    text: '#0b0b0b',
    textSecondary: '#52514e',
    textMuted: '#6b6a66',
    'ag-grid': '#eb6834',
    infinite: '#2a78d6',
  },
  dark: {
    surface: '#0d1117',
    border: '#30363d',
    baseline: '#484f58',
    text: '#f0efec',
    textSecondary: '#c3c2b7',
    textMuted: '#99a1b3',
    'ag-grid': '#d95926',
    infinite: '#3987e5',
  },
} as const;

type ChartRow = Row & { summary: Summary };

const CHART = {
  width: 760,
  padding: 20,
  /** room kept at the right of the longest bar, for its value */
  valueSpace: 120,
  barHeight: 14,
  barGap: 4,
  rowGap: 32,
  labelHeight: 20,
  radius: 4,
};

/** a bar anchored at the baseline: square at the left, rounded at the data end */
function barPath(x: number, y: number, width: number, height: number) {
  const r = Math.min(CHART.radius, width);
  const right = x + width;
  return (
    `M${x},${y}H${right - r}` +
    `a${r},${r} 0 0 1 ${r},${r}V${y + height - r}` +
    `a${r},${r} 0 0 1 ${-r},${r}H${x}Z`
  );
}

function renderChart(
  spec: ChartSpec,
  rows: ChartRow[],
  caption: string,
  themeName: keyof typeof THEMES,
) {
  const theme = THEMES[themeName];
  const { width, padding, barHeight, barGap } = CHART;
  const font = `font-family="system-ui, -apple-system, 'Segoe UI', Helvetica, Arial, sans-serif"`;
  const max = Math.max(
    ...rows.flatMap((row) => [row.summary.ag, row.summary.infinite]),
    0,
  );
  const barMax = width - padding * 2 - CHART.valueSpace;
  const out: string[] = [];

  let y = padding + 16;
  out.push(
    `<text x="${padding}" y="${y}" ${font} font-size="16" font-weight="600" fill="${
      theme.text
    }">${escapeXml(spec.title)}</text>`,
  );
  y += 20;
  out.push(
    `<text x="${padding}" y="${y}" ${font} font-size="13" fill="${
      theme.textMuted
    }">${escapeXml(caption)}</text>`,
  );

  // legend - identity is never carried by color alone
  y += 24;
  let legendX = padding;
  for (const grid of GRIDS) {
    out.push(
      `<rect x="${legendX}" y="${y - 10}" width="12" height="12" rx="3" fill="${
        theme[grid.key]
      }"/>`,
      `<text x="${legendX + 18}" y="${y}" ${font} font-size="13" fill="${
        theme.textSecondary
      }">${grid.name}</text>`,
    );
    legendX += 18 + grid.name.length * 7.2 + 20;
  }
  y += 14;

  for (const row of rows) {
    y += CHART.rowGap;
    const significant = row.summary.winner !== '≈';
    out.push(
      `<text x="${padding}" y="${y}" ${font} font-size="13" fill="${
        theme.textSecondary
      }">${escapeXml(row.label)}${
        significant
          ? ''
          : `<tspan dx="10" fill="${theme.textMuted}">no significant difference</tspan>`
      }</text>`,
    );
    y += CHART.labelHeight - 12;
    const top = y;
    for (const grid of GRIDS) {
      const value =
        grid.key === 'infinite' ? row.summary.infinite : row.summary.ag;
      const barWidth = max > 0 ? Math.max(1, (value / max) * barMax) : 1;
      out.push(
        `<path d="${barPath(
          padding,
          y,
          Math.round(barWidth * 10) / 10,
          barHeight,
        )}" fill="${theme[grid.key]}"/>`,
        `<text x="${Math.round(padding + barWidth + 8)}" y="${
          y + barHeight - 2.5
        }" ${font} font-size="13" fill="${theme.text}">${escapeXml(
          formatValue(value, row.summary.unit),
        )}</text>`,
      );
      y += barHeight + barGap;
    }
    y -= barGap;
    // the baseline both bars grow from
    out.push(
      `<line x1="${padding - 0.5}" y1="${top - 2}" x2="${padding - 0.5}" y2="${
        y + 2
      }" stroke="${theme.baseline}" stroke-width="1"/>`,
    );
  }

  const height = y + padding;
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img">\n` +
    `<title>${escapeXml(spec.title)}</title>\n` +
    `<rect x="0.5" y="0.5" width="${width - 1}" height="${
      height - 1
    }" rx="10" fill="${theme.surface}" stroke="${theme.border}"/>\n` +
    out.join('\n') +
    `\n</svg>\n`
  );
}

