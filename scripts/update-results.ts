type Summary = {
  /** the median of each grid that was measured */
  values: Partial<Record<GridName, number>>;
  /**
   * Infinite Table against each of the other grids: the one that does
   * better, or '≈' (no significant difference)
   */
  winners: Partial<Record<OtherGridName, GridName | '≈'>>;
  unit: string;
  better: 'lower' | 'higher';
};

type HistoryEntry = {
  versions: Partial<Record<GridName, string>>;
  date: string;
  chrome: string;
  headless: boolean;
  runs: number;
  machine: string;
  os: string;
  runner: string | null;
  /** `<size>/<scenario>/<metric key>` -> medians */
  metrics: Record<string, Summary>;
};

/**
 * Entries written when the benchmark had two grids look different:
 * `infinite` / `agGrid` for the versions, and `ag` / `infinite` / `winner`
 * for every metric.
 */
function normalizeEntry(raw: any): HistoryEntry {
  if (raw.versions) {
    return raw;
  }
  const { infinite, agGrid, metrics, ...rest } = raw;
  return {
    versions: { 'ag-grid': agGrid, infinite },
    ...rest,
    metrics: Object.fromEntries(
      Object.entries(metrics as Record<string, any>).map(([id, m]) => [
        id,
        {
          values: { 'ag-grid': m.ag, infinite: m.infinite },
          winners: {
            'ag-grid':
              m.winner === 'Infinite'
                ? 'infinite'
                : m.winner === 'AG Grid'
                  ? 'ag-grid'
                  : '≈',
          },
          unit: m.unit,
          better: m.better,
        },
      ]),
    ),
  };
}

