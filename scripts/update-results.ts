function formatNumber(value: number) {
  if (!Number.isFinite(value)) {
    return '–';
  }
  const abs = Math.abs(value);
  return value.toLocaleString('en-US', {
    maximumFractionDigits: abs >= 100 ? 0 : abs >= 10 ? 1 : 2,
  });
}

function formatValue(value: number, unit: string) {
  const text = formatNumber(value);
  if (!unit || text === '–') {
    return text;
  }
  return unit === '%' ? `${text}%` : `${text} ${unit}`;
}

/**
 * Infinite Table against one other grid, e.g. "**Infinite Table** 31% lower"
 * or "no significant difference"
 */
function describeDifference(s: Summary, other: OtherGridName) {
  const winner = s.winners[other];
  const infinite = s.values.infinite;
  const otherValue = s.values[other];
  if (winner == null || infinite == null || otherValue == null) {
    return null;
  }
  if (winner === '≈') {
    return 'no significant difference';
  }
  const name = `**${GRID_FULL_NAMES[winner]}**`;
  const best = winner === 'infinite' ? infinite : otherValue;
  const worst = winner === 'infinite' ? otherValue : infinite;
  if (s.unit === '%') {
    // already a percentage - give the difference in points
    const points = formatNumber(Math.abs(best - worst));
    return `${name} ${points} points ${s.better}`;
  }
  const base = s.better === 'lower' ? worst : best;
  if (!base) {
    return `${name} ${s.better}`;
  }
  const ratio = s.better === 'lower' ? worst / best : best / worst;
  if (Number.isFinite(ratio) && ratio >= 2) {
    return `${name} ${formatNumber(ratio)}× ${s.better}`;
  }
  const pct = Math.round((Math.abs(best - worst) / worst) * 100);
  return `${name} ${pct}% ${s.better}`;
}

/** Infinite Table against every other grid of a row, one per line */
function describeDifferences(s: Summary) {
  return OTHER_GRID_NAMES.map((other) => {
    const text = describeDifference(s, other);
    return text ? `vs ${GRID_FULL_NAMES[other]}: ${text}` : null;
  })
    .filter(Boolean)
    .join('<br>');
}

const escapeXml = (text: string) =>
  text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

